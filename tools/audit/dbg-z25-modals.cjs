const { chromium } = require('playwright');
const fs = require('fs');
const ACCT = JSON.parse(fs.readFileSync('/home/user/ff-user-panel/tools/tri-e2e/.state/d103.json','utf8'));
(async () => {
  const b = await chromium.launch({ args: ['--disable-dev-shm-usage','--mute-audio'] });
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
  await ctx.addInitScript(() => { try { localStorage.setItem('appLang','hi'); localStorage.setItem('tutorialSeen','1'); sessionStorage.setItem('vn_shown_this_launch','1'); } catch(e){} });
  const p = await ctx.newPage();
  await p.goto('https://deepsilence10161-source.github.io/ff-user-panel/index.html', { waitUntil: 'domcontentloaded', timeout: 60000 });
  await p.waitForFunction(() => window.auth && window.firebase, null, { timeout: 30000 });
  await p.evaluate(([e,w]) => window.auth.signInWithEmailAndPassword(e,w), [ACCT.qa1.email, ACCT.qa1.password]);
  await p.waitForFunction(() => window.U && window.curScr, null, { timeout: 30000 });
  await p.waitForTimeout(2500);
  const dismiss = async () => { try { const sg = p.locator('button:has-text("Samajh")'); const c = await sg.count(); for (let i = 0; i < c; i++) { const el = sg.nth(i); if (await el.isVisible()) { await el.click({ timeout: 3000, force: true }).catch(() => {}); await p.waitForTimeout(700); } } } catch (e) {} };
  await dismiss();
  await p.evaluate(() => window.navTo('special')); await p.waitForTimeout(3000); await dismiss();
  await p.screenshot({ path: 'reports/ui-sweep/z25-special.png' });
  await p.evaluate(() => { try { window.closeModal && window.closeModal(); } catch (e) {} });
  await p.evaluate(() => window.navTo('wallet')); await p.waitForTimeout(3500); await dismiss();
  await p.evaluate(() => window.showCoinShop && window.showCoinShop()); await p.waitForTimeout(1800);
  await p.screenshot({ path: 'reports/ui-sweep/z25-shop.png' });
  await p.evaluate(() => { try { window.closeCoinShop && window.closeCoinShop(); } catch (e) {} });
  await p.waitForTimeout(600);
  await p.evaluate(() => { try { window.startWd && window.startWd(); } catch (e) {} });
  await p.waitForTimeout(1800);
  await p.screenshot({ path: 'reports/ui-sweep/z25-wd.png' });
  console.log('SHOTS-OK');
  await b.close();
})();
